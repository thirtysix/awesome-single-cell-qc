#!/usr/bin/env python3
"""Write a proposal for scView from the hub. Offline.

For each scView row in exchange/scview-map.yaml, the hub records that back it
and that the row does not already cite, with their tier, PMID and the
benchmarks that evaluate them; then the citation corrections from the same
file. The output follows scView's `research/proposal-*.md` shape (a heading,
what it is based on, numbered items).

    python pipeline/scview_export.py [--scview FILE] [--map FILE] [--out FILE]

Writes exchange/scview-proposal-<date>.md. Nothing is written into scView:
copying the proposal there is the user's call.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

from config import DATA, ROOT, TIERS
from scview_import import (EXCHANGE, MAP, SCVIEW_CATALOG, load_map, load_scview,
                           row_pmids)

# Records in each row follow the schema's tier order: standard first, hypothesis last.
TIER_ORDER = {t: i for i, t in enumerate(TIERS)}


def suggestions(row: dict, record_ids: list[str], records: dict) -> list[dict]:
    """Mapped records the row does not already cite, strongest tier first."""
    cited = set(row_pmids(row))
    picked = [records[i] for i in record_ids if not records[i].get("pmid") or records[i]["pmid"] not in cited]
    return sorted(picked, key=lambda r: TIER_ORDER.get(r["tier"], len(TIER_ORDER)))


def cite(rec: dict) -> str:
    if rec.get("pmid"):
        return f"PMID {rec['pmid']}"
    if rec.get("doi"):
        return f"doi:{rec['doi']}"
    return rec.get("url") or rec.get("repo_url") or "no paper"


def record_line(rec: dict) -> str:
    line = f"- **{rec['name']}** ({rec['tier']}; {cite(rec)}): {rec['summary']}."
    if rec.get("benchmark_refs"):
        line += " Benchmarked in: " + "; ".join(b["name"] for b in rec["benchmark_refs"]) + "."
    if (rec.get("pmid") or rec.get("doi")) and not rec.get("verified"):
        line += " Citation not yet checked."
    return line


def render(rows: list[dict], mapping: dict, records: dict, date: str) -> str:
    by_id = {r["id"]: r for r in rows}
    out = [f"# Proposal: literature for the QC rows, from awesome-single-cell-qc ({date})", ""]
    mapped = [rid for rid in mapping["rows"] if rid in by_id]
    unbacked = [r["id"] for r in rows if not mapping["rows"].get(r["id"])]
    out += [
        "Not yet in `catalog-v2.tsv`. Generated by `pipeline/scview_export.py` in the hub from its curated "
        f"records; {len(rows)} rows of catalog-v2 in the QC-related categories were compared, "
        f"{len(mapped)} have hub records behind them, {len(unbacked)} do not "
        f"({', '.join(unbacked) or 'none'}). Each PMID or DOI below was matched to its title at "
        "Crossref or PubMed unless marked otherwise. "
        "Tiers: standard is in common use; benchmarked-sota won an independent benchmark; benchmarked "
        "was in one; published-unbenchmarked has only its own paper; hypothesis is untested.",
        "",
    ]

    out += ["## Citation corrections", ""]
    for n, c in enumerate(mapping["corrections"], 1):
        cited = f" (cites {c['pmid']})" if c.get("pmid") else ""
        out.append(f"{n}. **{c['row']}**{cited}: {c['problem']}. Fix: {c['fix']}.")
    out.append("")

    out += ["## Evidence to add, per row", ""]
    for rid in mapped:
        row = by_id[rid]
        picks = suggestions(row, mapping["rows"][rid], records)
        if not picks:
            continue
        out += [f"### {rid}: {row['idea']}", ""]
        out += [record_line(r) for r in picks]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scview", type=Path, default=SCVIEW_CATALOG)
    ap.add_argument("--catalog", type=Path, default=DATA / "catalog.json")
    ap.add_argument("--map", type=Path, default=MAP)
    ap.add_argument("--date", default=dt.date.today().isoformat())
    ap.add_argument("--out", type=Path)
    args = ap.parse_args(argv)

    if not args.scview.exists():
        print(f"scview-proposal: {args.scview} not found (set SCVIEW_CATALOG)", file=sys.stderr)
        return 1
    catalog = json.loads(args.catalog.read_text())
    records = {r["id"]: r for r in catalog["records"]}
    mapping = load_map(args.map, set(records))
    text = render(load_scview(args.scview), mapping, records, args.date)
    out = args.out or EXCHANGE / f"scview-proposal-{args.date}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    n_items = sum(1 for line in text.splitlines() if line.startswith("- **"))
    print(f"scview-proposal: {len(mapping['corrections'])} corrections, {n_items} record suggestions "
          f"-> {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
